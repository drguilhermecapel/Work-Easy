begin;
select no_plan();
select tests.setup_fixture();
create temp table dispatch_test(k text primary key,id uuid not null);
grant all on dispatch_test to authenticated;
create temp table drivers_test(driver_id uuid primary key,handle text);
grant select on drivers_test to authenticated;
insert into drivers_test values(tests.uid('provider_b'),'provider_b'),(tests.uid('client_b'),'client_b'),(tests.uid('provider_d'),'provider_d');
insert into public.ride_drivers(id,environment,vehicle,status,valid_until,reviewed_by,online)
 select driver_id,'simulation','sedan','approved',current_date+3,tests.uid('admin'),true from drivers_test;
update private.ride_network set module_enabled=true,quote_enabled=true,dispatch_enabled=true where environment='simulation';
update private.ride_dispatch_rules set wave_size=1 where environment='simulation';
create function pg_temp.request_trip(label text,origin_area text,dest_area text,ts timestamptz default null)
returns void language plpgsql as $$
declare q uuid;r uuid;
begin
 q:=(public.ride_quote(gen_random_uuid(),null,ts,jsonb_build_array(jsonb_build_object('origin',origin_area,'destination',dest_area,'payer','passenger')))->>'id')::uuid;
 r:=(public.ride_consent(q,true)->>'ride_id')::uuid;
 insert into dispatch_test values(label,r);
end $$;

savepoint waves;
select tests.authenticate_as('client_a');
select pg_temp.request_trip('journey','Saúde','Jabaquara');
select tests.clear_authentication();
insert into dispatch_test select 'leg',id from public.ride_legs where ride_id=(select id from dispatch_test where k='journey');
insert into dispatch_test select 'first',driver_id from private.ride_driver_offers where leg_id=(select id from dispatch_test where k='leg') and state='offered';
select is((select count(*) from private.ride_driver_offers where state='offered'),1::bigint,'leg event immediately targets one bounded wave');
select tests.authenticate_as((select handle from drivers_test where driver_id<>(select id from dispatch_test where k='first') order by driver_id desc limit 1));
insert into dispatch_test values('interested',auth.uid());
select ok(jsonb_array_length(public.driver_opportunities())>0,'eligible off-wave driver can see coarse radar');
select lives_ok($$select public.ride_register_interest((select id from dispatch_test where k='leg'))$$,'registering interest does not assign');
select throws_ok($$select public.ride_accept_offer((select id from dispatch_test where k='leg'),gen_random_uuid())$$,'P0001','offer_unavailable','cannot accept an offer that was not delivered');
select is(jsonb_array_length(public.ride_dashboard()->'offers'),0,'no active offer delivered to the radar participant yet');
select tests.authenticate_as((select handle from drivers_test where driver_id=(select id from dispatch_test where k='first')));
select lives_ok($$select public.ride_decline_offer((select id from dispatch_test where k='leg'),gen_random_uuid())$$,'refusal triggers next wave');
select tests.authenticate_as((select handle from drivers_test where driver_id=(select id from dispatch_test where k='interested')));
select is(jsonb_array_length(public.ride_dashboard()->'offers'),1,'interested eligible driver is contacted in the next wave');
select ok((public.ride_dashboard()->'offers'->0->>'trip_meters')::int=4400 and (public.ride_dashboard()->'offers'->0->>'approach_meters')::int=800,'snapshot distinguishes approach from occupied distance');
select throws_ok($$select public.driver_decide_offer((select id from dispatch_test where k='leg'),gen_random_uuid(),now()-interval '1 minute',true)$$,'P0001','offer_unavailable','obsolete delivered expiry cannot accept a renewed wave');
select tests.clear_authentication();
update private.ride_driver_offers set expires_at=statement_timestamp()-interval '5 seconds' where state='offered';
update private.ride_dispatch_rounds set next_scan=statement_timestamp()-interval '1 minute';
select private.recover_ride_dispatch();
select is((select count(*) from private.ride_driver_offers where state='expired'),1::bigint,'cron expires an unanswered offer');
select is((select count(*) from private.ride_driver_offers where state='offered'),1::bigint,'cron finds the remaining driver');
insert into dispatch_test select 'remaining',driver_id from private.ride_driver_offers where state='offered';
select tests.authenticate_as((select handle from drivers_test where driver_id=(select id from dispatch_test where k='remaining')));
select lives_ok($$select public.driver_save_preferences('Saúde',now()+interval '1 hour',50)$$,'driver sets private preferred destination and unit cost');
select is(jsonb_array_length(public.ride_dashboard()->'offers'),0,'opposite direction is removed');
select lives_ok($$select public.driver_save_preferences(null,null,50)$$,'driver cancels preference');
select is(jsonb_array_length(public.ride_dashboard()->'offers'),1,'compatible offer returns after preference changes');
select is((public.ride_dashboard()->'offers'->0->>'cost_cents')::int,260,'declared cost uses both approach and occupied km');
insert into dispatch_test values('accept',gen_random_uuid());
select lives_ok($$select public.driver_decide_offer((select id from dispatch_test where k='leg'),(select id from dispatch_test where k='accept'),
 (public.ride_dashboard()->'offers'->0->>'expires_at')::timestamptz,true)$$,'valid offer acceptance commits the driver');
select is(public.driver_decide_offer((select id from dispatch_test where k='leg'),(select id from dispatch_test where k='accept'),now(),true)->>'replayed','true','uncertain response repeats the same acceptance');
select lives_ok($$select public.ride_set_online(false)$$,'driver pauses after accepting');
select ok(jsonb_array_length(public.ride_dashboard()->'rides')>0,'obligation stays accessible while paused');
select tests.authenticate_as('client_a');
select ok((public.ride_dashboard()->'rides'->0->'legs'->0->>'pickup_estimate') is not null,'passenger receives own pickup estimate');
select throws_ok($$select public.driver_navigation((select id from dispatch_test where k='leg'))$$,'P0001','not_allowed','another role cannot read driver navigation');
select tests.clear_authentication();
select ok(not exists(select from public.ride_driver_inbox where driver_id=tests.uid('client_a')),'realtime carries no passenger inbox entry');
select is((select count(*) from private.ride_offer_history where state='assigned'),1::bigint,'exactly one assignment recorded');

rollback to waves;
savepoint airport;
select tests.authenticate_as('client_b');
insert into dispatch_test select 'terminal',(public.driver_preferences()->'terminals'->0->>'id')::uuid;
select throws_ok($$select public.driver_airport_queue((select id from dispatch_test where k='terminal'),true,0,0,1)$$,'P0001','outside_waiting_area','outside terminal is refused');
select lives_ok($$select public.driver_airport_queue((select id from dispatch_test where k='terminal'),true,-23.6191632,-46.6349565,10)$$,'inside terminal joins');
select is((public.driver_preferences()->'terminals'->0->>'position')::int,1,'first driver is first in line');
select lives_ok($$select public.driver_airport_queue((select id from dispatch_test where k='terminal'),true,-23.6191632,-46.6349565,10)$$,'re-entry without leaving renews the same position');
select tests.authenticate_as('provider_b');
select public.ride_set_online(true);
select public.driver_airport_queue((select id from dispatch_test where k='terminal'),true,-23.6191632,-46.6349565,10);
select is((public.driver_preferences()->'terminals'->0->>'position')::int,2,'second driver is second in line');
select tests.authenticate_as('client_b');
select public.driver_airport_queue((select id from dispatch_test where k='terminal'),false,null,null,null);
select public.driver_airport_queue((select id from dispatch_test where k='terminal'),true,-23.6191632,-46.6349565,10);
select is((public.driver_preferences()->'terminals'->0->>'position')::int,2,'leaving and rejoining returns to the tail');
select tests.authenticate_as('client_a');
select pg_temp.request_trip('airport','Terminal de ensaio','Saúde',now()+interval '3 hours');
select tests.clear_authentication();
insert into dispatch_test select 'airport_leg',id from public.ride_legs where ride_id=(select id from dispatch_test where k='airport');
select is((select driver_id from private.ride_driver_offers where leg_id=(select id from dispatch_test where k='airport_leg') and state='offered'),tests.uid('provider_b'),'only first eligible terminal driver is called');
select tests.authenticate_as('provider_b');
select public.ride_accept_offer((select id from dispatch_test where k='airport_leg'),gen_random_uuid());
select is(public.driver_navigation((select id from dispatch_test where k='airport_leg'))->>'phase','scheduled','exact destination is withheld until departure window');
select tests.authenticate_as('admin');
select throws_ok($$select public.driver_release_reservation((select id from dispatch_test where k='airport_leg'),gen_random_uuid(),true)$$,'P0001','invalid_transition','early reservation cannot be released as a no-show');
select tests.authenticate_as('provider_b');
select is((public.driver_preferences()->'terminals'->0->>'position'),null::text,'accepted terminal call leaves queue');
insert into dispatch_test values('release',gen_random_uuid());
select public.driver_release_reservation((select id from dispatch_test where k='airport_leg'),(select id from dispatch_test where k='release'));
select lives_ok($$select public.driver_release_reservation((select id from dispatch_test where k='airport_leg'),(select id from dispatch_test where k='release'))$$,'reservation release is idempotent after lost response');
select tests.authenticate_as('client_b');
select ok(exists(select from jsonb_array_elements(public.ride_dashboard()->'offers') o where o->>'leg_id'=(select id::text from dispatch_test where k='airport_leg')),'standby receives released reservation');
select public.ride_accept_offer((select id from dispatch_test where k='airport_leg'),gen_random_uuid());
select tests.clear_authentication();
update public.ride_legs set pickup_at=now()-interval '1 minute' where id=(select id from dispatch_test where k='airport_leg');
select private.recover_ride_dispatch();
select is((select count(*) from public.support_tasks where kind='ride_reservation_late'),1::bigint,'late reservation creates one contact task without silently cancelling');
select is((select status from public.ride_legs where id=(select id from dispatch_test where k='airport_leg')),'accepted','passenger commitment remains pending human verification');
select tests.authenticate_as('admin');
select lives_ok($$select public.driver_release_reservation((select id from dispatch_test where k='airport_leg'),gen_random_uuid(),true)$$,'operations can reassign a verified no-show after the scheduled time');
select tests.clear_authentication();
select is((select count(*) from private.ride_financial_accounts where leg_id=(select id from dispatch_test where k='airport_leg')),0::bigint,'no charge or payment generated by reservation substitution');
rollback to airport;
select tests.clear_authentication();
select tests.authenticate_as('client_a');
select pg_temp.request_trip('unavailable','Saúde','Vila Mariana');
select tests.clear_authentication();
update public.ride_legs set pickup_at=statement_timestamp()-interval '11 minutes' where ride_id=(select id from dispatch_test where k='unavailable');
update private.ride_dispatch_rounds set next_scan=now();
select private.recover_ride_dispatch();
select tests.authenticate_as('client_a');
select is((public.ride_dashboard()->'rides'->0->'legs'->0->>'dispatch_state'),'no_driver','deadline gives the passenger an explicit no-driver outcome');
select tests.clear_authentication();
select ok(exists(select from cron.job where jobname='workeasy-recover-driver-offers'),'cron recovery is installed');
select * from finish();
rollback;
